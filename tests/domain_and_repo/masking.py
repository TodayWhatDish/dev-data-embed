from app.domain.masking import mask


if __name__ == '__main__':
    # 카톡 표기 변형 - 자간 띄우기까지 잡되, 문장은 남는다
    for text in ['카톡 주세요', '카카오톡 아이디 알려드림', '까톡ㄱㄱ', '카 톡 으로', '카 카 오 톡 주소']:
        assert mask(text).startswith('[연락처]'), (text, mask(text))

    # 카/톡 이 들어가도 연락 수단이 아니면 남는다
    assert mask('카레맛 간식 잘 먹어요.') == '카레맛 간식 잘 먹어요.'
    assert mask('톡톡 소리나는 장난감 좋아해요') == '톡톡 소리나는 장난감 좋아해요'

    # 무엇을 가렸는지가 마크에 남는다 - 전화번호와 이메일은 다른 마크
    assert mask('구매는 010-1234-5678 로') == '구매는 [전화번호] 로', mask('구매는 010-1234-5678 로')
    assert mask('a.b+c@shop.co.kr 로 보냈어요') == '[이메일] 로 보냈어요', mask('a.b+c@shop.co.kr 로 보냈어요')

    # 필터 우회 - 앞자리 0 을 알파벳 O 로, 숫자를 한글로
    assert mask('O1O-1234-5678 이거로') == '[전화번호] 이거로', mask('O1O-1234-5678 이거로')
    # 한글 번호는 뒤 공백까지 먹는다 (자간 띄우기를 흡수하는 [\s-]* 때문)
    _hangul = '공일공 일이삼사 오육칠팔 로 전화주세요'
    assert mask(_hangul) == '[전화번호]로 전화주세요', mask(_hangul)

    # 마침표가 없어도 상품 설명은 살아남아야 한다 (문장째 지우면 글이 통째로 사라졌다)
    assert mask('강아지 사료 급처합니다 010-1234-5678로 연락주세요') \
        == '강아지 사료 급처합니다 [전화번호]로 연락주세요', mask('강아지 사료 급처합니다 010-1234-5678로 연락주세요')

    # '연락'·'문의' 는 그 자체로 연락처가 아니다. 평범한 후기를 지우면 안 된다
    assert mask('배송 문의 연락했더니 친절하게 답해주셨어요.') == '배송 문의 연락했더니 친절하게 답해주셨어요.'

    # SNS 아이디와 채널명 - 종류가 달라도 붙어 나오면 하나로 줄인다
    assert mask('인스타 @dogfood_shop 디엠 주세요') == '인스타 [연락처] 주세요', mask('인스타 @dogfood_shop 디엠 주세요')
    assert mask('오픈채팅으로 오세요') == '[연락처]으로 오세요', mask('오픈채팅으로 오세요')
    assert mask('010-1234-5678 카톡 주세요') == '[연락처] 주세요', mask('010-1234-5678 카톡 주세요')

    # 마크가 잇달아 나오면 하나로 뭉친다. 연락 수단은 종류가 달라도 [연락처] 로,
    # 그 밖의 마크는 '같은 종류가 반복될 때만' - 안 그러면 '[주소] [이름]' 이 한 덩어리가 된다
    _many = '010-1234-5678, a@b.co.kr / 오픈채팅 아무거나'
    assert mask(_many) == '[연락처] 아무거나', mask(_many)
    _two = '서울 강남구 역삼동, 경기 성남시 수정구 둘 다 가능'
    assert mask(_two) == '[주소] 둘 다 가능', mask(_two)
    _mix = '부산 연제구 고분로 144 최형재입니다'
    assert mask(_mix) == '[주소] [이름]입니다', mask(_mix)

    # 주소는 목록 없이 잡는다 - 행정구역이 두 단계 이상 이어질 때만
    for text in ['서울특별시 강남구 삽니다', '경기 성남시 삽니다', '강남구 역삼동 삽니다']:
        assert mask(text) == '[주소] 삽니다', (text, mask(text))
    assert mask('서울 강남구 테헤란로 12 로 보내주세요') == '[주소] 로 보내주세요', mask('서울 강남구 테헤란로 12 로 보내주세요')

    # 한 단계짜리 평범한 말은 주소가 아니다
    assert mask('사료를 이동하면서 급여했어요') == '사료를 이동하면서 급여했어요'
    assert mask('부산 맛집처럼 유명해요') == '부산 맛집처럼 유명해요'

    # 이름은 호칭·자기소개가 붙은 자리만 - 목록 없이 잡는다
    assert mask('박승호입니다 잘 부탁해요') == '[이름]입니다 잘 부탁해요', mask('박승호입니다 잘 부탁해요')
    assert mask('홍길동님 감사합니다') == '[이름]님 감사합니다', mask('홍길동님 감사합니다')
    assert mask('김철수 사장님 친절해요') == '[이름] 사장님 친절해요', mask('김철수 사장님 친절해요')

    # 이름처럼 생긴 평범한 말은 남는다 (성씨로 시작하는 낱말이 후기에 널렸다)
    for text in ['우리 강아지 정말 좋아해요', '고객님 응대가 최고입니다', '장난감입니다 진짜 좋아요',
                 '배송비 무료라 좋아요', '주인님 소리에 반응해요',
                 '처음엔 먹다가 금방 남기더라고요']:  # 후기 2000건 중 106건이 이 '-더라고요' 였다
        mask_text = mask(text)
        print(text + ' : ' + mask_text)
        assert mask_text == text, (text, mask_text)

    # DB 로 이미 아는 이름은 인자로 더 지운다. 긴 것부터 지워야 짧은 이름이 먼저 먹지 않는다
    assert mask('김철수와 김철수네 강아지', names=('김철수', '김철수네')) == '[이름]와 [이름] 강아지'

    # 자간 벌리기는 공백만이 아니다 - 기호를 끼워 넣는 우회
    assert mask('오@픈@채@팅 하실분') == '[연락처] 하실분', mask('오@픈@채@팅 하실분')
    assert mask('오_픈_채_팅 하실분') == '[연락처] 하실분', mask('오_픈_채_팅 하실분')

    # 문장부호는 구분자가 아니다 - 넣으면 '오! 카레맛' 이 '오카' 가 된다
    assert mask('오! 카레맛 좋아요') == '오! 카레맛 좋아요', mask('오! 카레맛 좋아요')
    assert mask('오, 카레 급여중') == '오, 카레 급여중', mask('오, 카레 급여중')
    assert mask('010~1231~1241 로 주세요') == '[전화번호] 로 주세요', mask('010~1231~1241 로 주세요')

    # 휴대폰만이 아니다 - 지역번호·070·080·0505 도 전화번호다
    for _t in ['031-111-1111', '02-123-4567', '0212345678', '070 8888 9999',
               '0505-111-2222', '080-123-4567']:
        assert mask(_t) == '[전화번호]', (_t, mask(_t))

    # 숫자가 값인 문장은 전화번호가 아니다 (국번을 \d{2,3} 으로 열면 여기가 무너진다)
    for _t in ['2026.08.13 에 샀어요', '3000원에 1200g 이에요', '하루 2번 300g 씩']:
        assert mask(_t) == _t, (_t, mask(_t))

    # 낱말 사이에 숫자를 끼우는 우회도 받는다. '오카'는 뒤에 한글이 붙으면 낱말로 본다
    assert mask('오@픈          채2팅방 초대') == '[연락처]방 초대', mask('오@픈          채2팅방 초대')
    assert mask('오카방 초대할게요') == '[연락처] 초대할게요', mask('오카방 초대할게요')
    assert mask('사료 오픈 500그램 채워 주세요') == '사료 오픈 500그램 채워 주세요'

    # 주소는 이어지는 만큼 한 덩어리로 (조각내면 [주소] [주소] 가 된다)
    _addr = '주소: 경기 성남시 수정구 수정로 163 입니다'
    assert mask(_addr) == '주소: [주소] 입니다', mask(_addr)

    # 조사가 붙은 이름도 잡는다. 두 글자 반려동물 이름은 남는다
    assert mask('곽두팔이가 잘 먹어요') == '[이름]이가 잘 먹어요', mask('곽두팔이가 잘 먹어요')
    assert mask('구름이가 잘 먹어요') == '구름이가 잘 먹어요', mask('구름이가 잘 먹어요')

    assert mask('오 픈 채 팅 주세요') == '[연락처] 주세요', mask('오 픈 채 팅 주세요')
    

    t1 = "박승호입니다 오 픈 채 팅 주세요 010-1234-1234 충남 아산시 배방읍"
    a1 = mask(t1)
    t2 = "한인뽕입니다 오                     픈채 팅 주세요 공일공-일오삼일-일이삼사 제주 제주시 노형로 184010@tukorea.ac.kr"
    a2 = mask(t2)
    t3 = "허재쏭입니다 디엠 @winter_dog 주세요  전남광주 진도군 진도읍 지도길 266 manager@tukorea.ac.kr"
    a3 = mask(t3)
    t4 = "진도개인 우리 아이 곽두팔이가 장이 많이 안좋아요. 그래서 '삼성'제품을 써봤는데 싹 났더라고요. 공구 하실분 오@픈@채@팅 010~1231~1241, 주소: 경기 성남시 수정구 수정로 163 메일: 호날두@samsungaxi.com"
    a4 = mask(t4)
    t5 = "안녕하세요, **삼성**AXI 대표 최형재입니다. 수강 들을 실 분들은 031-111-1111로 전화 문의 또는 호날두@samsungaxi.com으로 메일 주세요. 문의 이후에 오@픈          채2팅방 초대 해드리겠습니다. 학원 주소: 부산 연제구 고분로 144"
    a5 = mask(t5)
    t6 = '급하면 010-1234-5678 카톡 @dogfood_shop 셋 중 아무거나'
    a6 = mask(t6) # ([전화번호] [연락처] [아이디] -> [연락처])
    # 띄어쓰기는 개수를 안 막는다 - 대놓고 벌려 쓰는 게 기호 우회보다 흔하다
    t7 = '오                     픈채 팅 주세요'
    a7 = mask(t7)
    assert mask(t7) == a7, mask(t7)

    print(t1 + '\n' + a1 + '\n')
    print(t2 + '\n' + a2 + '\n')
    print(t3 + '\n' + a3 + '\n')
    print(t4 + '\n' + a4 + '\n')
    print(t5 + '\n' + a5 + '\n')
    print(t6 + '\n' + a6 + '\n')

    assert mask('') == '' and mask(None) is None

    # 오탐 상한선. 규칙을 조일수록 여기가 먼저 터진다 — '라고' 하나가 106건을 먹은 적이 있다.
    # 여기 걸리면 규칙이 과한 것이거나, 더미 후기에 진짜 개인정보가 섞인 것이다. 눈으로 보고 정한다
    # import csv, pathlib
    # seed = pathlib.Path('data/seed/review.csv')
    # if seed.exists():
    #     bodies = [r['body'] for r in csv.DictReader(seed.open(encoding='utf-8'))]

    #     eaten = []
    #     for b in bodies:
    #         mask_text = mask(b)
    #         print(b + " : " + mask_text)
            
    # 규칙별로 무엇이 걸렸는지 눈으로 본다. 정규식만 봐서는 어디까지 무는지 감이 안 온다
    from app.domain.masking import _RULES
    _demo = ('박승호입니다 오@픈 채2팅 010~1231~1241 '
             'a@shop.co.kr 부산 연제구 고분로 144')
    for _pat, _repl in _RULES:
        for _hit in _pat.findall(_demo):
            print(f'  {_repl:8} <- {_hit!r}')
    print(' ', mask(_demo))

    print('masking self-check OK')
