# 날짜/시각 컬럼은 TEXT ISO-8601 이다 - 형식은 CHECK 정규식으로만 강제한다.
# CHECK 안에서 ::date 로 캐스팅하지 않는다: 형식이 틀리면 check_violation(23514) 이 아니라
# DataError 로 터져 QueryError 매핑을 빠져나간다(400 이 아니라 500).
# 달력에 없는 날(2021-02-30)은 정규식이 못 거른다 - API(app/api/schemas.py)가 거른다.
DATE_RE = r"'^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$'"
DATETIME_RE = r"'^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01]) ([01]\d|2[0-3]):[0-5]\d:[0-5]\d$'"
